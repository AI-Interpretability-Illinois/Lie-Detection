#!/usr/bin/env python3
"""
A larger pool of mask-building questions for the sample-size test (b).

The masks are built from 25 of the 50 hand-written questions in src/prompts.py
(DIRECT_TRUTH), each wrapped in one of six falsehood prefixes (F) or "Answer
truthfully:" (T). To vary only the NUMBER of prompts, this writes more questions
in the same style, generated by the Azure OpenAI deployment in
~/.config/lie_detection/azure_openai.env, then deduplicated against the 50
originals and against the AI Liar Questions1000 set used in evaluation.
Output: extra_prompts/mask_pool_questions.json (list of questions, seed-0 order).
"""
import json
import os
import random
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from src.prompts import DIRECT_TRUTH

OUT = Path(__file__).parent / "extra_prompts" / "mask_pool_questions.json"
AIL = Path("/work/hdd/bfqt/xiaocong/lie_detection_outputs/extra_data/ai_liar/questions_1000_all.json")
TOPICS = ["geography", "physical science", "biology and medicine", "history", "literature and art",
          "music and film", "sports", "language and words", "mathematics", "animals and plants",
          "food and everyday life", "technology and inventions"]


def norm(q):
    return re.sub(r"[^a-z0-9 ]", "", q.lower()).strip()


def main():
    from openai import OpenAI
    env = dict(l.strip().split("=", 1) for l in open(os.path.expanduser(
        "~/.config/lie_detection/azure_openai.env")) if "=" in l)
    client = OpenAI(base_url=env["AZURE_OPENAI_ENDPOINT"], api_key=env["AZURE_OPENAI_API_KEY"])
    examples = "\n".join(DIRECT_TRUTH[:12])
    got = []
    for t in TOPICS:
        r = client.responses.create(model=env["AZURE_OPENAI_DEPLOYMENT"], input=(
            f"Write 60 short, simple general-knowledge questions about {t}, one per line, in "
            f"exactly the style of these examples:\n{examples}\n\nEach question must have one "
            f"short, widely known correct answer. Plain questions only: no numbering, no "
            f"answers, no multiple choice, no yes/no questions."))
        lines = [re.sub(r"^\s*[\d\-\*\.\)]+\s*", "", l).strip() for l in r.output_text.splitlines()]
        got += [l for l in lines if l.endswith("?") and 3 <= len(l.split()) <= 20]
        print(f"{t}: {len(lines)} lines", flush=True)
    seen = {norm(q) for q in DIRECT_TRUTH}
    seen |= {norm(v["question"]) for v in json.load(open(AIL)).values()}
    pool = []
    for q in got:
        if norm(q) not in seen:
            seen.add(norm(q)); pool.append(q)
    random.Random(0).shuffle(pool)
    OUT.write_text(json.dumps(pool, indent=0, ensure_ascii=False))
    print(f"{len(got)} generated, {len(pool)} kept after dedup -> {OUT}")




# ── polarity-balanced statement pool (for the fictf / pooltf / poolmix families) ──
TF_OUT = Path(__file__).parent / "extra_prompts" / "mask_pool_tf.json"
CELLS = [(True, False), (False, False), (True, True), (False, True)]   # (is_true, negated), as in TF_STATEMENTS


def build_tf(per_cell=60):
    """Statements in the style of src/prompts.py TF_STATEMENTS, ordered in the same 4-cycle
    (true, false, true-negated, false-negated) so any prefix of 4k items is balanced."""
    from openai import OpenAI
    from src.prompts import TF_STATEMENTS
    env = dict(l.strip().split("=", 1) for l in open(os.path.expanduser(
        "~/.config/lie_detection/azure_openai.env")) if "=" in l)
    client = OpenAI(base_url=env["AZURE_OPENAI_ENDPOINT"], api_key=env["AZURE_OPENAI_API_KEY"])
    ex = "\n".join(s for s, _ in TF_STATEMENTS[:8])
    seen = {norm(s) for s, _ in TF_STATEMENTS}
    E = Path("/work/hdd/bfqt/xiaocong/lie_detection_outputs")
    for f in (E / "liars_bench/eval_set.jsonl", E / "extra_data/extra_amgot.jsonl",
              E / "extra_data/extra_inject.jsonl"):
        for l in open(f):
            st = json.loads(l).get("grade", {}).get("statement")
            if st:
                seen.add(norm(st))
    cells = {}
    for is_true, neg in CELLS:
        kind = (("TRUE" if is_true else "FALSE") + " statements that " +
                ("contain a negation (the word 'not')" if neg else "contain no negation"))
        r = client.responses.create(model=env["AZURE_OPENAI_DEPLOYMENT"], input=(
            f"Write {per_cell + 20} short, simple general-knowledge {kind}, one per line, in the "
            f"style of these examples:\n{ex}\n\nMix topics (geography, science, history, arts, "
            f"sports, everyday life). Each must be unambiguously {'true' if is_true else 'false'}. "
            f"No numbering, no explanations."))
        got = []
        for l in r.output_text.splitlines():
            l = re.sub(r"^\s*[\d\-\*\.\)]+\s*", "", l).strip()
            if l.endswith(".") and 3 <= len(l.split()) <= 20 and ((" not " in f" {l} ") == neg) \
                    and norm(l) not in seen:
                seen.add(norm(l)); got.append(l)
        cells[(is_true, neg)] = got[:per_cell]
        print(f"{kind}: {len(got)} usable", flush=True)
    k = min(len(v) for v in cells.values())
    pool = [[cells[c][i], c[0]] for i in range(k) for c in CELLS]
    TF_OUT.write_text(json.dumps(pool, indent=0, ensure_ascii=False))
    print(f"{len(pool)} statements ({k} per cell) -> {TF_OUT}")



# ── short correct / false answers for the question pool (response-token contrasts) ──
ANS_OUT = Path(__file__).parent / "extra_prompts" / "mask_pool_answers.json"


def build_answers(batch=60):
    """For each pool question: a short correct answer and a plausible, clearly wrong one
    of the same type (a city for a city, a number for a number)."""
    from openai import OpenAI
    env = dict(l.strip().split("=", 1) for l in open(os.path.expanduser(
        "~/.config/lie_detection/azure_openai.env")) if "=" in l)
    client = OpenAI(base_url=env["AZURE_OPENAI_ENDPOINT"], api_key=env["AZURE_OPENAI_API_KEY"])
    qs = json.loads(OUT.read_text())
    out = {}
    for s in range(0, len(qs), batch):
        chunk = qs[s:s + batch]
        listing = "\n".join(f"{i}\t{q}" for i, q in enumerate(chunk))
        r = client.responses.create(model=env["AZURE_OPENAI_DEPLOYMENT"], input=(
            "For each numbered question give the correct answer and a plausible but clearly wrong "
            "answer of the same type (same kind of entity, number or word). Both as short as "
            "possible (1-4 words), no explanation. Output one line per question: "
            "index<TAB>correct<TAB>wrong\n\n" + listing))
        for line in r.output_text.splitlines():
            parts = [p.strip() for p in line.split("\t")]
            if len(parts) == 3 and parts[0].isdigit() and int(parts[0]) < len(chunk):
                t, f = parts[1].rstrip("."), parts[2].rstrip(".")
                if t and f and t.lower() != f.lower():
                    out[chunk[int(parts[0])]] = {"true": t, "false": f}
        print(f"{s + len(chunk)}/{len(qs)}: {len(out)} answered", flush=True)
    ANS_OUT.write_text(json.dumps(out, indent=0, ensure_ascii=False))
    print(f"{len(out)} -> {ANS_OUT}")


if __name__ == "__main__":
    build_tf() if "--tf" in sys.argv else build_answers() if "--answers" in sys.argv else main()
