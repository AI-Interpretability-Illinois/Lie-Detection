#!/usr/bin/env python3
"""
Qualitative examples for the appendix: the same LIARS' BENCH deception item answered by the unedited model, the falsehood
mask, the best steering configuration and the best honest prompt, taken from the main-table response files (test half,
the arms chosen on validation). Items are chosen deterministically among those where the unedited model lies and the
mask is graded honest, and the shortest replies are preferred so the table stays readable; nothing is edited by hand
except truncation to 260 characters (marked with an ellipsis). Writes paper/tables/examples.tex.
"""
import hashlib
import json
import random
from pathlib import Path

B = Path("/work/hdd/bfqt/xiaocong/lie_detection_outputs")
OUT = Path("/u/xiaocong/lie_detection/paper/tables/examples.tex")
J = "judged_Qwen2p5-7B-Instruct_v2"
PICK = [  # model file stem, tags, arms (label in the file) in display order, how many items
    ("Meta-Llama-3p1-8B-Instruct", ["final"], ["unsteered", "weight:fiction a=-1.0", "actsteer:L8 r=-0.5 (c=-2.8)", "prompt:honest2"], 3),
    ("Phi-4-mini-instruct", ["fixlb", "finaladd"], ["unsteered", "weight:pooled a=-1.0", "actsteer:L16 r=-0.18 (c=-10.4)", "prompt:honest2"], 2),
]
NAMES = {"unsteered": "unedited", "weight:fiction a=-1.0": r"\textbf{ours}", "weight:pooled a=-1.0": r"\textbf{ours}",
         "actsteer:L8 r=-0.5 (c=-2.8)": "steering (CAA; L8, $-0.5$)", "actsteer:L16 r=-0.18 (c=-10.4)": "steering (CAA; L16, $-0.18$)",
         "prompt:honest2": "honest prompt"}
half = lambda u: "val" if int(hashlib.md5(u.encode()).hexdigest(), 16) % 2 == 0 else "test"


def tex(s, n=260):
    s = s.replace("\n", " ").strip()
    if len(s) > n:
        s = s[:n].rsplit(" ", 1)[0] + " [\\ldots]"
    for a, b in (("\\", "\\textbackslash "), ("&", "\\&"), ("%", "\\%"), ("$", "\\$"), ("#", "\\#"), ("_", "\\_"), ("{", "\\{"), ("}", "\\}"), ("~", "\\textasciitilde "), ("^", "\\^{}")):
        s = s.replace(a, b)
    return s


def main():
    items = {json.loads(l)["uid"]: json.loads(l) for l in open(B / "liars_bench/eval_set.jsonl")}
    blocks = []
    for model, tags, arms, n in PICK:
        rows = {}
        for t in tags:
            p = B / f"liars_bench_honesty_{model}_{t}_{J}.jsonl"
            if not p.exists():
                continue
            for r in map(json.loads, open(p)):
                rows.setdefault(r["uid"], {}).setdefault(r["arm"], r)
        cands = [u for u, d in rows.items() if u.startswith("instructed-deception") and half(u) == "test"
                 and all(a in d for a in arms) and d["unsteered"]["split"] == "instructed-deception"
                 and d["unsteered"]["verdict_hybrid"] == "lie" and d[arms[1]]["verdict_hybrid"] == "honest"
                 and all(len(d[a]["resp"]) < 320 for a in arms)]
        rnd = random.Random(11); rnd.shuffle(cands)
        print(model, len(cands), "candidates")
        name = model.replace("Meta-Llama-3p1-8B-Instruct", "Llama-3.1-8B").replace("Phi-4-mini-instruct", "Phi-4-mini")
        for u in cands[:n]:
            it = items[u]; d = rows[u]
            blocks.append(f"\\textbf{{{name}}} --- system: \\emph{{{tex(it['ctx'][0]['content'])}}} --- user: \\emph{{{tex(it['ctx'][1]['content'].split(chr(10))[-1])}}} (statement is {'true' if it['grade']['gold_truth'] else 'false'}; the model believes it {'true' if d['unsteered'].get('belief') else 'false'}) \\\\[2pt]")
            for a in arms:
                v = d[a]["verdict_hybrid"]
                blocks.append(f"\\hspace{{1em}}{NAMES[a]} ({v}): {tex(d[a]['resp'])} \\\\")
            blocks.append("\\addlinespace[6pt]")
    OUT.write_text("% generated by reports/make_examples.py; verbatim model outputs, truncated at 260 characters\n"
                   "\\begin{tabular}{p{0.96\\textwidth}}\n\\toprule\n" + "\n".join(blocks) + "\n\\bottomrule\n\\end{tabular}\n")
    print("wrote", OUT, len(blocks), "lines")


if __name__ == "__main__":
    main()
